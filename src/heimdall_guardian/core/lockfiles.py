"""Manifests that list only direct dependencies (no lockfile next to them).

Dependencies are checked offline and without resolving anything (P2, P3), so a manifest
with no lockfile leaves its transitive dependencies unchecked. Pure logic: it only reads
file names and, for `requirements*.txt`, the start of the file.
"""

from __future__ import annotations

import re
from pathlib import Path, PurePosixPath

# manifest name (lower case) -> lockfile names (lower case) any of which makes it complete
_LOCKS: dict[str, frozenset[str]] = {
    "package.json": frozenset(
        {"package-lock.json", "npm-shrinkwrap.json", "yarn.lock", "pnpm-lock.yaml", "bun.lockb"}
    ),
    "composer.json": frozenset({"composer.lock"}),
    "pyproject.toml": frozenset({"uv.lock", "poetry.lock", "pipfile.lock", "pdm.lock"}),
    "pipfile": frozenset({"uv.lock", "poetry.lock", "pipfile.lock", "pdm.lock"}),
    "setup.py": frozenset({"uv.lock", "poetry.lock", "pipfile.lock", "pdm.lock"}),
    "gemfile": frozenset({"gemfile.lock"}),
    "cargo.toml": frozenset({"cargo.lock"}),
    "go.mod": frozenset({"go.sum"}),
    "pubspec.yaml": frozenset({"pubspec.lock"}),
    "podfile": frozenset({"podfile.lock"}),
    "package.swift": frozenset({"package.resolved"}),
}

_MAX_READ = 256 * 1024
_GENERATED = re.compile(
    r"autogenerated by pip-compile|uv pip compile|uv export|^\s*#\s*via\b|--hash=",
    re.IGNORECASE | re.MULTILINE,
)


def _is_requirements(relative: str) -> bool:
    path = PurePosixPath(relative)
    name = path.name.lower()
    if not name.endswith(".txt"):
        return False
    if name == "requirements.txt" or name.startswith("requirements-"):
        return True
    return path.parent.name.lower() == "requirements"


def _looks_complete(root: Path, relative: str) -> bool:
    """Does the requirements file look generated with all its transitive dependencies?"""
    try:
        with (root / relative).open("rb") as handle:
            text = handle.read(_MAX_READ).decode("utf-8", errors="ignore")
    except OSError:
        return False
    return bool(_GENERATED.search(text))


def direct_only_manifests(root: Path, files: list[str]) -> list[str]:
    """Relative paths of the manifests whose folder has no matching lockfile."""
    present = {file.lower() for file in files}
    found: list[str] = []
    for relative in sorted(files):
        path = PurePosixPath(relative)
        if "node_modules" in path.parts:
            continue
        name = path.name.lower()
        locks = _LOCKS.get(name)
        if locks is not None:
            folder = path.parent
            if not any(str(folder / lock).lower() in present for lock in locks):
                found.append(relative)
        elif _is_requirements(relative) and not _looks_complete(root, relative):
            found.append(relative)
    return found
