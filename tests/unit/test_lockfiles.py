"""Direct-only manifest notice and the databases location (HDL_BASES_DIR)."""

from __future__ import annotations

from pathlib import Path

import pytest

from heimdall_guardian.adapters.base import missing_database
from heimdall_guardian.core.lockfiles import direct_only_manifests
from heimdall_guardian.core.paths import bases_dir
from heimdall_guardian.core.profiles import Module
from heimdall_guardian.core.runner import build_plan
from heimdall_guardian.i18n import render


def _tree(root: Path, files: dict[str, str]) -> list[str]:
    for name, content in files.items():
        target = root / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
    return sorted(files)


@pytest.mark.parametrize(
    ("manifest", "lock"),
    [
        ("package.json", "package-lock.json"),
        ("package.json", "npm-shrinkwrap.json"),
        ("package.json", "yarn.lock"),
        ("package.json", "pnpm-lock.yaml"),
        ("package.json", "bun.lockb"),
        ("composer.json", "composer.lock"),
        ("pyproject.toml", "uv.lock"),
        ("pyproject.toml", "poetry.lock"),
        ("Pipfile", "Pipfile.lock"),
        ("setup.py", "pdm.lock"),
        ("Gemfile", "Gemfile.lock"),
        ("Cargo.toml", "Cargo.lock"),
        ("go.mod", "go.sum"),
        ("pubspec.yaml", "pubspec.lock"),
        ("Podfile", "Podfile.lock"),
        ("Package.swift", "Package.resolved"),
    ],
)
def test_manifest_with_and_without_its_lockfile(tmp_path: Path, manifest: str, lock: str):
    alone = _tree(tmp_path, {f"app/{manifest}": ""})
    assert direct_only_manifests(tmp_path, alone) == [f"app/{manifest}"]
    both = _tree(tmp_path, {f"app/{lock}": ""})
    assert direct_only_manifests(tmp_path, [*alone, *both]) == []


def test_lockfile_must_be_in_the_same_folder(tmp_path: Path):
    files = _tree(tmp_path, {"a/composer.json": "{}", "b/composer.lock": "{}"})
    assert direct_only_manifests(tmp_path, files) == ["a/composer.json"]


def test_lockfile_name_is_case_insensitive(tmp_path: Path):
    files = _tree(tmp_path, {"Gemfile": "", "gemfile.lock": ""})
    assert direct_only_manifests(tmp_path, files) == []


def test_package_json_in_node_modules_is_ignored(tmp_path: Path):
    files = _tree(tmp_path, {"node_modules/x/package.json": "{}"})
    assert direct_only_manifests(tmp_path, files) == []


def test_plain_requirements_are_direct_only(tmp_path: Path):
    files = _tree(
        tmp_path,
        {
            "requirements.txt": "flask==3.0.0\n",
            "requirements-dev.txt": "pytest==8.0.0\n",
            "requirements/prod.txt": "django==5.0\n",
            "notes.txt": "x",
        },
    )
    assert direct_only_manifests(tmp_path, files) == [
        "requirements-dev.txt",
        "requirements.txt",
        "requirements/prod.txt",
    ]


@pytest.mark.parametrize(
    "content",
    [
        "# This file is autogenerated by pip-compile with Python 3.12\nflask==3.0.0\n",
        "# uv pip compile requirements.in\nflask==3.0.0\n",
        "# uv export --format requirements-txt\nflask==3.0.0\n",
        "flask==3.0.0\n    # via -r requirements.in\n",
        "flask==3.0.0 \\\n    --hash=sha256:abc\n",
    ],
)
def test_generated_requirements_are_not_direct_only(tmp_path: Path, content: str):
    files = _tree(tmp_path, {"requirements.txt": content})
    assert direct_only_manifests(tmp_path, files) == []


def _demo(root: Path) -> None:
    _tree(root, {"app/requirements.txt": "flask==3.0.0\n", "web/composer.json": "{}"})


def test_plan_limitation_present_with_dependencies(tmp_path: Path):
    from heimdall_guardian.core.runner import _plan_limitations

    _demo(tmp_path)
    plan = build_plan(tmp_path, profile="custom", custom_modules=frozenset({Module.DEP}))
    notes = [n for n in _plan_limitations(plan) if n["code"] == "core.limit.direct_only"]
    assert len(notes) == 1
    assert notes[0]["params"]["count"] == 2
    assert "transitive" in render(notes[0], "en")
    assert "transitivas" in render(notes[0], "es")


def test_plan_limitation_absent_without_dependencies(tmp_path: Path):
    from heimdall_guardian.core.runner import _plan_limitations

    _demo(tmp_path)
    plan = build_plan(tmp_path, profile="custom", custom_modules=frozenset({Module.SAST}))
    assert all(n["code"] != "core.limit.direct_only" for n in _plan_limitations(plan))


def test_bases_dir_override(monkeypatch: pytest.MonkeyPatch, tmp_path: Path):
    assert bases_dir().name == "bases"
    monkeypatch.setenv("HDL_BASES_DIR", str(tmp_path / "otras"))
    assert bases_dir() == tmp_path / "otras"


def test_missing_database_says_where_it_looked_and_hints_when_isolated(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
):
    note = missing_database()
    assert note["params"]["path"] == str(bases_dir())
    assert str(bases_dir()) in render(note, "en")
    assert "HDL_BASES_DIR" in render(note, "en")  # HDL_DATA_DIR is set by the fixture
    assert "HDL_BASES_DIR" in render(note, "es")
    monkeypatch.setenv("HDL_BASES_DIR", str(tmp_path / "x"))
    text = render(missing_database(), "en")
    assert str(tmp_path / "x") in text
    assert "HDL_DATA_DIR is set" not in text
    monkeypatch.delenv("HDL_BASES_DIR")
    monkeypatch.delenv("HDL_DATA_DIR")
    assert "HDL_DATA_DIR is set" not in render(missing_database(), "en")
